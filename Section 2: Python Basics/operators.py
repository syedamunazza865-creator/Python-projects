#Arithmetic (+ - * / // % **)
num1=12
num2=3
print(num1+num2)
print(num1-num2)
print(num1*num2)
print(num1/num2) #quotient in float
print(num1//num2) ##quotient in int
print(num1%num2)  #remainder 
print(num1**num2)
#comparision (== != > < >= <=)
print(num1==num2)
print(num1!=num2)
print(num1>num2)
print(num1<num2)
print(num1>=num2)
print(num1<=num2)
#logical ( and or not) 
print(num1>15 or num1==12)
print(not(True))
